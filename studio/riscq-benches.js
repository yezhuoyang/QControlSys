/**
 * Microwave signals at a step: one entry per open drive, readout or acquisition window, with the
 * converter → apparatus wire it travels and the delay of that wire from the binding.
 */
export function microwaveAt(bundle, state) {
  const bindings = bindingIndex(bundle), out = [];
  for (const window of state?.openWindows ?? []) {
    const binding = bindings.get(window.core + "/" + window.channel + "/" + window.slot);
    if (!binding) continue;
    const acquire = window.kind === "demod" || binding.detail?.kind === "acquire";
    const carrier = acquire ? null : carrierHz(bundle, window.freq);
    const amp = ampFraction(window.amp), phase = phaseRad(window.phase ?? 0);
    const kind = binding.detail?.kind;
    out.push({
      id: "mw:" + window.id, part: binding.part, channel: window.part, converter: window.converter, kind,
      wire: acquire ? { from: binding.part, to: window.converter } : { from: window.converter, to: binding.part },
      carrierHz: carrier, ampFraction: amp, phaseRad: phase, delayPs: binding.delayPs ?? 0,
      window: { id: window.id, opens: window.opens, closes: window.closes, source: window.source },
      hover: [
        ["Signal", acquire ? "returning readout signal, demodulated on " + window.converter : kind + " pulse from " + window.converter + " to " + binding.part],
        ...(carrier !== null ? [["Carrier", fmt(carrier / 1e9, 7) + " GHz (DAC code " + window.freq + ")"]] : [["Carrier", "the readout tone, demodulated at the ADC"]]),
        ["Amplitude", fmt(amp * 100, 4) + " % of full scale"],
        ["Phase", fmt(phase, 4) + " rad"],
        ["Wire delay", fmt((binding.delayPs ?? 0) / 1000, 5) + " ns"],
        ["Window", window.id + ": batches " + window.opens + " – " + window.closes],
        ...(window.source ? [["Instruction", window.source]] : []),
      ],
    });
  }
  return out;
}

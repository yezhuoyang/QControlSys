// Optical benches of the three platforms, and the light that is on at a step of a run.
//
// A bench is the light-delivery hardware of a platform: lasers, modulators, fibers, lenses,
// mirrors, AODs and objectives, placed in a table frame. riscq-optics.js traces each train of
// a bench as Gaussian beams. `beamsAt` reads which pulse windows of the trace are open, finds
// the apparatus part each window drives through `program.bindings`, and returns the beams that
// window switches on, with the RF and power the window's codes set. So a beam in the 3D view is
// on exactly while the controller's DAC window that drives it is open.
//
// Frames: the table frame is in mm with z up and its origin where the sample frame has its
// origin (neutral: ZAC (0, 0) µm in the atom plane; QCCD: Studio (0, 0) on the trap surface).
// The sample frame is the apparatus frame of machine.geometry (riscq/geometry.mjs). Every
// number below carries its source; "assumed" marks a choice of this project, "derived" marks
// arithmetic on other entries. Superconducting machines have no light: `microwaveAt` lists the
// microwave signals on the coax instead.
import * as O from "./riscq-optics.js";


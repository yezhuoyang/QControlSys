// ───────────────────────────── codes of the trace ─────────────────────────────
const AMP_SCALE = 19896, BATCH_SIZE = 16; // riscq/soc.mjs
const dspHz = (bundle) => 1e12 / bundle.machine.dspPeriodPs;
/** DAC carrier in Hz of a 16-bit frequency code: the inverse of soc.mjs freqCode, read as 0 … rate. */
export const carrierHz = (bundle, code) => (((code % 65536) + 65536) % 65536) * BATCH_SIZE * dspHz(bundle) / 65536;
/** Amplitude fraction of full scale of an amplitude code (soc.mjs ampCode). */
export const ampFraction = (code) => Math.abs(code) / AMP_SCALE;
/** Phase in rad of a 16-bit phase code in units of π (soc.mjs phaseCode). */
export const phaseRad = (code) => ((((code + 32768) & 0xffff) - 32768) / 32768) * Math.PI;

function bindingIndex(bundle) {
  return new Map((bundle.program?.bindings ?? []).map((b) => [b.core + "/" + b.channel + "/" + b.slot, b]));
}

// ───────────────────────────── neutral atoms ─────────────────────────────
function neutralBench(bundle) {
  const P = PARAMETERS.neutral, geo = bundle.machine.geometry ?? {};
  const hzPerUm = geo.calibration?.hertzPerMicrometre ?? P.hzPerUm.value;
  const fObj = P.objectiveFMm.value, f1 = P.relayF1Mm.value, v = P.acousticMPerS.value, lambda = P.aodLambdaNm.value;
  // x_focus = f_obj (f1/f2) λ Δf / v must equal Δf / (Hz per µm).
  const f2 = (f1 * fObj * 1e-3 * lambda * 1e-9 * hzPerUm * 1e6) / v;
  const zT = P.tableHeightMm.value, vertical = zT - fObj;
  const plane = { point: [0, 0, 0], normal: [0, 0, 1] };
  const toTable = (um) => [um[0] / 1000, um[1] / 1000, (um[2] ?? 0) / 1000];
  const toSample = (mm) => [mm[0] * 1000, mm[1] * 1000, (mm[2] ?? 0) * 1000];
  const objective = { ...O.objective({ fMm: fObj, na: P.objectiveNa.value }), label: "objective", source: P.objectiveNa.source };
  const lasers = [
    { id: "aod-laser", name: "AOD tweezer laser", lambdaNm: lambda, powerW: P.aodPowerW.value, transition: "far-off-resonant trap light for 87Rb", source: P.aodLambdaNm.source },
    { id: "slm-laser", name: "SLM tweezer laser", lambdaNm: P.slmLambdaNm.value, powerW: P.slmPowerW.value, transition: "far-off-resonant trap light for 87Rb", source: P.slmLambdaNm.source },
    { id: "rydberg-420", name: "Rydberg laser, first leg", lambdaNm: P.rydberg420Nm.value, powerW: P.rydberg420PowerW.value, transition: "87Rb 5S1/2 → 6P3/2", source: P.rydberg420Nm.source },
    { id: "rydberg-1013", name: "Rydberg laser, second leg", lambdaNm: P.rydberg1013Nm.value, powerW: P.rydberg1013PowerW.value, transition: "87Rb 6P3/2 → 53S1/2", source: P.rydberg1013Nm.source },
    { id: "raman", name: "Raman laser", lambdaNm: P.ramanNm.value, powerW: P.ramanPowerW.value, transition: "87Rb hyperfine qubit, near the D1 line", source: P.ramanNm.source },
  ];
  const laser = (id) => lasers.find((l) => l.id === id);
  // AOD trains: AOD x, AOD y, a 4f relay telescope f1–f2, a beam splitter that joins the two AOD
  // branches, the dichroic that joins the SLM light, a periscope mirror down to the objective.
  // The relay images the AODs onto the objective pupil, so a deflection becomes a focus shift
  // f_obj · θ · f1/f2 in the atom plane.
  const aodTrain = (k, signs = { x: 1, y: 1 }) => {
    const label = (axis) => "aod" + k + " " + axis;
    const rf = { vAcousticMPerS: v, apertureMm: 10, efficiency: 0.8, centreHz: P.aodCentreHz.value, source: P.acousticMPerS.source };
    const head = [
      { ...O.aod({ ...rf, axis: "x", sign: signs.x }), at: 30, label: label("x") },
      { ...O.aod({ ...rf, axis: "y", sign: signs.y }), at: 10, label: label("y") },
      { ...O.lens(f1), at: f1, label: "relay lens 1 (aod" + k + ")", source: P.relayF1Mm.source },
      { ...O.lens(f2), at: f1 + f2, label: "relay lens 2 (aod" + k + ")", source: P.relayF2Mm.source },
    ];
    // From relay lens 2 to the objective is f2: along the table to the periscope, then down.
    const toSplitter = f2 - vertical - 100;
    const tail = [
      { ...O.beamSplitter({ transmission: 0.5, ...(k % 2 ? { normal: [1, -1, 0] } : {}) }), at: toSplitter, label: "beam splitter (AOD branches)", source: "assumed" },
      { ...O.mirror({ normal: [1, 0, 1] }), at: 100, label: "periscope mirror", source: "assumed" },
      { ...O.dichroic({ transmission: 0.95 }), at: 50, label: "dichroic (810 / 850 nm)", source: "assumed" },
      { ...objective, at: vertical - 50 },
    ];
    const upstream = 30 + 10 + f1 + (f1 + f2) + toSplitter;
    // Branch 0 runs along +x; branch 1 along +y and is folded into +x by the splitter.
    const start = k % 2 ? [-100, -upstream, zT] : [-(upstream + 100), 0, zT];
    const dir = k % 2 ? [0, 1, 0] : [1, 0, 0];
    return {
      source: O.gaussian({ lambdaNm: lambda, w0Um: P.aodBeamRadiusUm.value, powerW: P.aodPowerW.value, name: "aod-laser" }),
      start, dir, xAxis: [0, 0, -1], elements: [...head, ...tail], plane,
    };
  };
  // A higher RF moves the spot toward +x and +y of the ZAC frame: mount each AOD that way.
  const calibrated = (k) => {
    const probe = aodTrain(k);
    const signs = {};
    for (const axis of ["x", "y"]) {
      const t = O.traceTrain(probe, { rfHz: { ["aod" + k + " " + axis]: P.aodCentreHz.value + 1e6 } });
      signs[axis] = t.plane.at[axis === "x" ? 0 : 1] >= 0 ? 1 : -1;
    }
    return aodTrain(k, signs);
  };
  const aods = (geo.aods ?? []).map((a) => a.id);
  const trains = aods.map((k) => ({ id: "aod" + k, device: "aod" + k, laser: "aod-laser", role: "tweezer", label: "AOD " + k + " tweezers", train: calibrated(k), source: P.aodLambdaNm.source }));
  // SLM tweezers: one train to the origin; the array of foci is every trap of the geometry.
  trains.push({
    id: "slm", device: null, laser: "slm-laser", role: "static tweezers", label: "SLM tweezer array", traps: geo.traps ?? [], source: P.slmLambdaNm.source,
    train: {
      source: O.gaussian({ lambdaNm: P.slmLambdaNm.value, w0Um: 4000, powerW: P.slmPowerW.value }), start: [600, 0, zT - 50], dir: [-1, 0, 0], xAxis: [0, 0, 1], plane,
      elements: [
        { ...O.beamSplitter({ transmission: 0.9 }), at: 100, label: "SLM (phase pattern not modeled)", source: "assumed" },
        { ...O.dichroic({ transmission: 0.95, normal: [-1, 0, 1] }), at: 500, label: "dichroic (810 / 850 nm)", source: "assumed" },
        { ...objective, at: vertical - 50 },
      ],
    },
  });
  // Rydberg and Raman: global beams in the atom plane, shaped by cylindrical lenses.
  const zone = (geo.zones ?? []).find((z) => z.kind === "entanglement") ?? { origin: [0, 0], size: [100, 100] };
  const zc = [zone.origin[0] + zone.size[0] / 2, zone.origin[1] + zone.size[1] / 2];
  const sheet = (id, laserId, from, wzUm, wyUm, extra = {}) => {
    const l = laser(laserId), wIn = 1000, path = 1500;
    // f = π w_in w_target / λ makes a waist w_target of a collimated beam of radius w_in.
    const f = (w) => (Math.PI * wIn * w) / (l.lambdaNm * 1e-3) / 1000;
    const fz = f(wzUm), fy = f(wyUm);
    const centre = toTable([...zc, 0]);
    const dir = [from, 0, 0];
    const els = [
      { ...O.aom({ centreHz: P.aomCentreHz.value, efficiency: 0.85 }), at: 50, label: id + " AOM", source: P.aomCentreHz.source },
      ...[[fy, "y", "cylindrical lens (in-plane width)"], [fz, "x", "cylindrical lens (sheet height)"]].sort((a, b) => b[0] - a[0])
        .map(([fv, axis, name]) => ({ ...O.cylLens(fv, axis), label: id + " " + name, fAt: path - fv, source: "derived: f = π w_in w / λ" })),
    ];
    let last = 0;
    for (const e of els) {
      const atAbs = e.fAt ?? e.at;
      e.at = atAbs - last;
      last = atAbs;
      delete e.fAt;
    }
    return {
      source: O.gaussian({ lambdaNm: l.lambdaNm, w0Um: wIn, powerW: l.powerW, name: laserId }),
      start: [centre[0] - from * path, centre[1], 0], dir, xAxis: [0, 0, 1], elements: els, endMm: 1, plane: { point: centre, normal: dir }, ...extra,
    };
  };
  trains.push(
    { id: "rydberg-420", device: "beam:rydberg", laser: "rydberg-420", role: "rydberg", label: "Rydberg 420 nm sheet", train: sheet("rydberg-420", "rydberg-420", 1, P.rydbergSheetHeightUm.value, P.rydbergSheetWidthUm.value), source: P.rydberg420Nm.source },
    { id: "rydberg-1013", device: "beam:rydberg", laser: "rydberg-1013", role: "rydberg", label: "Rydberg 1013 nm sheet (counter-propagating)", train: sheet("rydberg-1013", "rydberg-1013", -1, P.rydbergSheetHeightUm.value, P.rydbergSheetWidthUm.value), source: P.rydberg1013Nm.source },
  );
  // Raman: one round global beam across the whole array, focused by a spherical lens.
  const extent = geo.extent ?? [[0, 0], [300, 400]];
  const mid = [(extent[0][0] + extent[1][0]) / 2, (extent[0][1] + extent[1][1]) / 2];
  const ramanF = (Math.PI * 1000 * P.ramanWaistUm.value) / (P.ramanNm.value * 1e-3) / 1000;
  trains.push({
    id: "raman", device: "beam:raman", laser: "raman", role: "raman", label: "Raman global beam", source: P.ramanNm.source,
    train: {
      source: O.gaussian({ lambdaNm: P.ramanNm.value, w0Um: 1000, powerW: P.ramanPowerW.value, name: "raman" }),
      start: [mid[0] / 1000, mid[1] / 1000 - (ramanF + 100), 0], dir: [0, 1, 0], xAxis: [0, 0, 1], endMm: 1, plane: { point: [mid[0] / 1000, mid[1] / 1000, 0], normal: [0, 1, 0] },
      elements: [
        { ...O.aom({ centreHz: P.aomCentreHz.value, efficiency: 0.85 }), at: 50, label: "raman AOM", source: P.aomCentreHz.source },
        { ...O.lens(ramanF), at: 50, label: "raman focusing lens", source: "derived: f = π w_in w / λ" },
      ],
    },
  });
  return {
    platform: "neutral",
    frames: { table: "mm, z up, origin at the ZAC (0, 0) µm point of the atom plane, where the objective axis meets it", sample: "ZAC architecture µm (machine.geometry)" },
    toTable, toSample, lasers, trains, parameters: { ...P, relayF2Mm: { ...P.relayF2Mm, value: f2 } },
    calibration: { hzPerUm, centreHz: P.aodCentreHz.value, effectiveFocalMm: (fObj * f1) / f2 },
    notes: [
      "The AOD bench reproduces the run's tone calibration by construction: f2 is derived so that f_obj · (f1/f2) · λ/v equals 1/(Hz per µm).",
      "Rydberg beams are SLM top-hats in the cited experiment; they are traced here as Gaussian sheets of the same height.",
      "Static SLM tweezers are one train to the origin; their foci are the trap grids of the geometry.",
    ],
  };
}

// ───────────────────────────── trapped ions (QCCD) ─────────────────────────────
function qccdBench(bundle) {
  const P = PARAMETERS.qccd, geo = bundle.machine.geometry ?? {};
  const umPerUnit = geo.units?.micrometresPerUnit ?? P.micrometresPerUnit.value;
  const h = P.ionHeightUm.value / 1000;
  const toTable = (p) => [(p[0] * umPerUnit) / 1000, (p[1] * umPerUnit) / 1000, h];
  const toSample = (mm) => [(mm[0] * 1000) / umPerUnit, (mm[1] * 1000) / umPerUnit];
  const lasers = [
    { id: "raman-370", name: "Raman gate laser", lambdaNm: P.ramanNm.value, powerW: P.ramanPowerW.value, transition: "171Yb+ hyperfine qubit, stimulated Raman", source: P.ramanNm.source },
    { id: "detect-369", name: "Detection laser", lambdaNm: P.detectNm.value, powerW: P.detectPowerW.value, transition: "171Yb+ 2S1/2 – 2P1/2 cycling", source: P.detectNm.source },
    { id: "cool-493", name: "Sympathetic cooling laser", lambdaNm: P.coolNm.value, powerW: P.coolPowerW.value, transition: "138Ba+ 6S1/2 – 6P1/2", source: P.coolNm.source },
  ];
  const fiberW = P.fiberMfdUm.value / 2, fc = P.collimatorFMm.value;
  /** Fiber-delivered beam focused onto a point from direction `dir` in the plane of the surface. */
  const delivered = (laserId, target, dir, waistUm, id) => {
    const l = lasers.find((x) => x.id === laserId);
    const wColl = O.waistAfterLensUm(fiberW, fc, l.lambdaNm); // collimated radius after the collimator
    const fFocus = (Math.PI * wColl * waistUm) / (l.lambdaNm * 1e-3) / 1000;
    const before = 20 + 10 + fc + 150 + fFocus;
    const d = Math.hypot(...dir), u = dir.map((x) => x / d);
    return {
      source: O.gaussian({ lambdaNm: l.lambdaNm, w0Um: 500, powerW: l.powerW, name: laserId }),
      start: target.map((x, k) => x - u[k] * before), dir: u, xAxis: [0, 0, 1], endMm: 2, plane: { point: target, normal: u },
      elements: [
        { ...O.aom({ centreHz: P.aomCentreHz.value, efficiency: 0.8 }), at: 20, label: id + " AOM", source: P.aomCentreHz.source },
        { ...O.fiber({ mfdUm: P.fiberMfdUm.value, couplingEfficiency: 0.6 }), at: 10, label: id + " fiber", source: P.fiberMfdUm.source },
        { ...O.lens(fc), at: fc, label: id + " collimator", source: P.collimatorFMm.source },
        { ...O.lens(fFocus), at: 150, label: id + " focusing lens", source: "derived: f = π w_coll w / λ for the waist " + waistUm + " µm" },
      ],
    };
  };
  const sites = geo.sites ?? [];
  const gateSites = sites.filter((s) => s.gate);
  const trains = [];
  const r = Math.SQRT1_2;
  for (const s of gateSites) {
    const at = toTable(s.position);
    trains.push(
      { id: "raman:" + s.id, device: "site:" + s.id, kinds: ["rotate", "ms"], laser: "raman-370", role: "gate", label: "Raman gate beam on " + s.id, site: s.id, train: delivered("raman-370", at, [r, r, 0], P.gateWaistUm.value, "raman " + s.id), source: P.ramanNm.source },
      { id: "detect:" + s.id, device: "site:" + s.id, kinds: ["detect"], laser: "detect-369", role: "detect", label: "Detection beam on " + s.id, site: s.id, train: delivered("detect-369", at, [r, -r, 0], P.gateWaistUm.value, "detect " + s.id), source: P.detectNm.source },
    );
  }
  // Broadcast cooling: one beam along the trap axis through the gate sites.
  if (gateSites.length) {
    const xs = gateSites.map((s) => toTable(s.position)), y = xs.reduce((a, p) => a + p[1], 0) / xs.length;
    const cx = (Math.min(...xs.map((p) => p[0])) + Math.max(...xs.map((p) => p[0]))) / 2;
    trains.push({ id: "cool", device: "light:cooling", kinds: ["cool"], laser: "cool-493", role: "cool", label: "Sympathetic cooling beam", train: delivered("cool-493", [cx, y, h], [1, 0, 0], P.coolWaistUm.value, "cool"), source: P.coolNm.source });
  }
  return {
    platform: "qccd",
    frames: { table: "mm, z up, origin at QCCD Studio (0, 0) on the trap surface; ions at the RF null " + P.ionHeightUm.value + " µm above it", sample: "QCCD Studio architecture units of " + umPerUnit + " µm (machine.geometry)" },
    toTable, toSample, lasers, trains, parameters: P,
    imaging: { na: P.imagingNa.value, fMm: P.imagingFMm.value, source: P.imagingNa.source },
    notes: [
      "Beams run parallel to the trap surface at the ion height and address a whole gate zone (Pino et al. 2021).",
      "Gate beams cross the trap axis at 45°, detection beams at −45°; the angles are assumed.",
      "Electrode voltages are electrical and are drawn by the stage, not traced here.",
    ],
  };
}

// ───────────────────────────── bench of a run ─────────────────────────────
/** The optical bench of a run's platform. Superconducting machines have none. */
export function benchFor(bundle) {
  if (bundle.platform === "neutral") return neutralBench(bundle);
  if (bundle.platform === "qccd") return qccdBench(bundle);
  return {
    platform: bundle.platform, lasers: [], trains: [], parameters: {}, frames: {},
    notes: [bundle.platform === "superconducting" ? "Microwave drive through coax: see microwaveAt and the wires of the design." : "This platform has no optical bench."],
  };
}

/**
 * Every optical element of a bench with its position in the table frame, traced with no RF
 * drive, for drawing the bench when no beam is on. Elements shared by trains appear once.
 */
export function benchElements(bench) {
  const out = new Map();
  for (const t of bench.trains) {
    const traced = O.traceTrain(t.train);
    out.set("source:" + t.id, { label: (t.label ?? t.id) + " source", kind: "source", at: t.train.start, train: t.id, laser: t.laser });
    for (const e of traced.elements) {
      const key = e.label + "@" + e.at.map((v) => v.toFixed(3)).join(",");
      if (!out.has(key)) out.set(key, { ...e, train: t.id });
    }
  }
  return [...out.values()];
}

const fmt = (v, digits = 4) => (Number.isFinite(v) ? String(Number(v.toPrecision(digits))) : "—");
const power = (w) => (w >= 1 ? fmt(w) + " W" : w >= 1e-3 ? fmt(w * 1e3) + " mW" : fmt(w * 1e6) + " µW");
const intensity = (x) => (x >= 1e6 ? fmt(x / 1e6) + " MW/cm²" : x >= 1e3 ? fmt(x / 1e3) + " kW/cm²" : fmt(x) + " W/cm²");

function hoverOf({ label, laser, traced, rfHz, window, binding, device }) {
  const f = traced.focus;
  return [
    ["Beam", label],
    ["Laser", laser.name + " (" + laser.transition + ")"],
    ["Wavelength", fmt(laser.lambdaNm) + " nm"],
    ["Optical frequency", fmt(traced.opticalHz / 1e12, 9) + " THz"],
    ["RF drive", rfHz.map((x) => fmt(x / 1e6, 7) + " MHz").join(" · ")],
    ["Power at the focus", power(traced.powerW)],
    ["Waist at the focus", fmt(f.wxUm) + " × " + fmt(f.wyUm) + " µm"],
    ["Rayleigh range", fmt(f.zRxUm) + " × " + fmt(f.zRyUm) + " µm"],
    ["Peak intensity", intensity(f.peakWcm2)],
    ...(traced.plane ? [["Radius at the target", fmt(traced.plane.wxUm) + " × " + fmt(traced.plane.wyUm) + " µm"]] : []),
    ...(traced.warnings.length ? [["Warning", traced.warnings.join(" ")]] : []),
    ...(window ?[["Window", window.id + ": batches " + window.opens + " – " + window.closes]] : []),
    ...(window?.source ? [["Instruction", window.source]] : []),
    ...(binding ? [["Binding", binding.id + " → " + device]] : []),
  ];
}

/**
 * The beams on at a step. state = riscq-model.js stateAt(bundle, index); extra.tones = Map of
 * tone channel ("aod0.x1") → µm, as model.tonesAt gives them. Returns
 * [{ id, device, trainId, on, kind, lambdaNm, opticalHz, rfHz, powerW, window, binding, geometry, hover, … }].
 * A neutral-atom tweezer is one beam per pair of active column and row tones of an AOD, focused
 * at their crossing. A QCCD detection window also yields a fluorescence cone toward the PMT.
 */
export function beamsAt(bundle, bench, state, extra = {}) {
  if (!bench?.trains?.length || !state) return [];
  const bindings = bindingIndex(bundle), out = [];
  const lasers = new Map(bench.lasers.map((l) => [l.id, l]));
  const tones = extra.tones instanceof Map ? extra.tones : new Map(Object.entries(extra.tones ?? {}));
  const aodOpen = new Map();
  for (const window of state.openWindows ?? []) {
    const binding = bindings.get(window.core + "/" + window.channel + "/" + window.slot);
    if (!binding) continue;
    if (/^aod\d+:[xy]\d+$/.test(binding.part)) {
      aodOpen.set(window.part, { window, binding });
      continue;
    }
    const kind = binding.detail?.kind;
    for (const t of bench.trains.filter((x) => x.device === binding.part && (!x.kinds || x.kinds.includes(kind)))) {
      const laser = lasers.get(t.laser), rf = carrierHz(bundle, window.freq);
      const aomLabel = t.train.elements.find((e) => e.kind === "aom")?.label;
      const aomHz = rf || t.train.elements.find((e) => e.kind === "aom")?.centreHz;
      const traced = O.traceTrain(t.train, { rfHz: aomLabel ? { [aomLabel]: aomHz } : {}, powerFraction: ampFraction(window.amp) });
      out.push({
        id: t.id + "@" + window.id, device: binding.part, trainId: t.id, on: true, kind, role: t.role, label: t.label,
        lambdaNm: laser.lambdaNm, opticalHz: traced.opticalHz, rfHz: aomHz, powerW: traced.powerW,
        window: { id: window.id, opens: window.opens, closes: window.closes, source: window.source, part: window.part },
        binding: binding.id, geometry: traced,
        hover: hoverOf({ label: t.label, laser, traced, rfHz: [aomHz], window, binding, device: binding.part }),
      });
      if (kind === "detect" && bench.imaging) {
        const ionAt = traced.plane?.at ?? traced.focus.at;
        out.push({
          id: "fluorescence:" + t.site + "@" + window.id, device: binding.part, trainId: t.id, on: true, kind: "fluorescence", role: "fluorescence",
          label: "Fluorescence of " + t.site + " to the PMT array", lambdaNm: laser.lambdaNm,
          cone: { apex: ionAt, axis: [0, 0, 1], halfAngleRad: Math.asin(bench.imaging.na), lengthMm: bench.imaging.fMm },
          pmt: "zone." + t.site + ".pmt", window: { id: window.id, opens: window.opens, closes: window.closes, source: window.source, part: window.part },
          hover: [["Light", "369.5 nm fluorescence of the ions in " + t.site], ["Collected by", "imaging objective NA " + bench.imaging.na + " (assumed) onto PMT channel zone." + t.site + ".pmt"],
            ["Bright or dark", "set by the measured state: the PMT channel's counts in the trace say which"], ["Window", window.id + ": batches " + window.opens + " – " + window.closes]],
        });
      }
    }
  }
  // Neutral-atom tweezers at every crossing of an active column tone and row tone of one AOD.
  if (bench.platform === "neutral") {
    const { hzPerUm, centreHz } = bench.calibration, laser = lasers.get("aod-laser");
    for (const aodGeo of bundle.machine.geometry?.aods ?? []) {
      const train = bench.trains.find((t) => t.id === "aod" + aodGeo.id);
      const cols = aodGeo.columns.filter((c) => aodOpen.has(c) && tones.has(c)), rows = aodGeo.rows.filter((r) => aodOpen.has(r) && tones.has(r));
      for (const c of cols)
        for (const r of rows) {
          const fx = centreHz + hzPerUm * tones.get(c), fy = centreHz + hzPerUm * tones.get(r);
          const wc = aodOpen.get(c), wr = aodOpen.get(r);
          const frac = (ampFraction(wc.window.amp) * ampFraction(wr.window.amp)) / (cols.length * rows.length);
          const traced = O.traceTrain(train.train, { rfHz: { ["aod" + aodGeo.id + " x"]: fx, ["aod" + aodGeo.id + " y"]: fy }, powerFraction: frac });
          const id = "tweezer:aod" + aodGeo.id + ":" + c.split(".")[1] + "*" + r.split(".")[1];
          const label = "AOD " + aodGeo.id + " tweezer at column tone " + c + " × row tone " + r;
          out.push({
            id, device: "aod" + aodGeo.id, trainId: train.id, on: true, kind: wc.binding.detail?.kind, role: "tweezer", label,
            tones: [c, r], focusUm: bench.toSample(traced.plane.at).slice(0, 2),
            lambdaNm: laser.lambdaNm, opticalHz: traced.opticalHz, rfHz: [fx, fy], powerW: traced.powerW,
            window: { id: wc.window.id, opens: wc.window.opens, closes: wc.window.closes, source: wc.window.source, part: c },
            binding: wc.binding.id, geometry: traced,
            hover: [...hoverOf({ label, laser, traced, rfHz: [fx, fy], window: wc.window, binding: wc.binding, device: wc.binding.part }),
              ["Spot in the atom plane", bench.toSample(traced.plane.at).slice(0, 2).map((v) => fmt(v, 6)).join(", ") + " µm"]],
          });
        }
    }
  }
  return out;
}


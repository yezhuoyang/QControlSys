// The compiled union-find decoder (riscq/decoders/uf_decoder.c) for a circuit: its decoding
// graph as C tables, the build for a RISC-Q core with clang, and its runs in the Lean model.
//
// The graph comes from the circuit itself (bridge/magic_sim.py mode "graph"): detectors and
// observables as XORs of measurement bits, the edges of its detector error model. The same C
// source runs two ways:
//   bench   cases in RAM, one decode after another; every decode's start and end time, its
//           correction and work are stored to the host window. This is how the decoder is
//           calibrated: decode times over real syndromes, and the correction compared with
//           PyMatching's on the same shots.
//   in-run  a decoder core of a control system (riscq/decoders/inrun.mjs builds its tables).
//
// Times are core batches: one per instruction plus the model's branch and bus penalties
// (riscq/soc.mjs `model`), at the build's clock.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { socSpec, program, execute } from "../soc.mjs";
import { loadElf } from "../rv32.mjs";
import { compileC, mapHeader, linkerScript, runtimeDir } from "../toolchain.mjs";

const IMAGES = fileURLToPath(new URL("../../validation/ftqvm/decoder-images/", import.meta.url));

const SOURCE = new URL("./uf_decoder.c", import.meta.url);
const arr = (type, name, values) => `static const ${type} ${name}[${Math.max(1, values.length)}] = { ${values.length ? values.join(", ") : "0"} };`;

/** CSR adjacency of the graph's nodes (detectors and the boundary, the last node). */
function adjacency(graph) {
  const nodes = graph.detectors.length + 1, boundary = nodes - 1;
  const lists = Array.from({ length: nodes }, () => []);
  graph.edges.forEach(([a, b], e) => { lists[a].push(e); lists[b < 0 ? boundary : b].push(e); });
  const start = [0];
  for (const l of lists) start.push(start.at(-1) + l.length);
  return { start, edges: lists.flat() };
}

/** The generated header: sizes and tables of a graph, and the mode's own tables. */
export function header(graph, mode) {
  const D = graph.detectors.length, boundary = D;
  const detStart = [0];
  for (const ms of graph.detectors) detStart.push(detStart.at(-1) + ms.length);
  const obsStart = [0];
  for (const ms of graph.observables) obsStart.push(obsStart.at(-1) + ms.length);
  const adj = adjacency(graph);
  const lines = [
    "/* GENERATED by riscq/decoders/uf.mjs: the decoding graph of one circuit. */",
    mode.kind === "bench" ? "#define UF_BENCH 1" : "#define UF_INRUN 1",
    `#define UF_MEAS ${graph.measurements}`, `#define UF_DET ${D}`, `#define UF_EDGES ${graph.edges.length}`, `#define UF_OBS ${graph.observables.length}`,
    arr("uint16_t", "det_start", detStart), arr("uint16_t", "det_meas", graph.detectors.flat()), arr("uint8_t", "det_ref", graph.detRef),
    arr("uint16_t", "edge_a", graph.edges.map(([a]) => a)), arr("uint16_t", "edge_b", graph.edges.map(([, b]) => (b < 0 ? boundary : b))),
    arr("uint32_t", "edge_obs", graph.edges.map(([, , o]) => o >>> 0)),
    arr("uint16_t", "adj_start", adj.start), arr("uint16_t", "adj_edge", adj.edges),
    arr("uint16_t", "obs_start", obsStart), arr("uint16_t", "obs_meas", graph.observables.flat()),
  ];
  if (graph.errors) {
    // The cluster decoder (UF_HYPER): error mechanisms with their detectors, and each detector's errors.
    const errStart = [0];
    for (const [ds] of graph.errors) errStart.push(errStart.at(-1) + ds.length);
    const lists = Array.from({ length: D }, () => []);
    graph.errors.forEach(([ds], e) => ds.forEach((x) => lists[x].push(e)));
    const dStart = [0];
    for (const l of lists) dStart.push(dStart.at(-1) + l.length);
    // Weights: −ln(p/(1−p)), scaled by 16 and rounded (an error twice as likely weighs 11 less).
    const weight = (p) => Math.max(1, Math.round(16 * Math.log((1 - p) / Math.max(p, 1e-12))));
    lines.push("#define UF_HYPER 1", `#define UF_ERRS ${graph.errors.length}`, `#define UF_HMAXR ${mode.maxRows ?? 96}`, `#define UF_HMAXC ${mode.maxCols ?? 256}`,
      `#define UF_HEXACT ${mode.exact ?? 10}`, arr("uint8_t", "err_w", graph.errors.map(([, , p]) => Math.min(255, weight(p)))),
      arr("uint16_t", "err_start", errStart), arr("uint16_t", "err_det", graph.errors.flatMap(([ds]) => ds)), arr(graph.observables.length <= 8 ? "uint8_t" : "uint32_t", "err_obs", graph.errors.map(([, o]) => o >>> 0)),
      arr("uint16_t", "dadj_start", dStart), arr("uint16_t", "dadj_err", lists.flat()));
  }
  if (mode.kind === "bench") {
    // Cases packed eight bits to a byte, bit j of a case in bit j % 8 of its byte j / 8.
    const bytes = Math.ceil(graph.measurements / 8);
    const packed = mode.cases.flatMap((s) => Array.from({ length: bytes }, (_, k) => [...s.slice(8 * k, 8 * k + 8)].reduce((v, c, i) => v | (Number(c) << i), 0)));
    lines.push(`#define UF_CASES ${mode.cases.length}`, `#define UF_CASE_BYTES ${bytes}`, arr("uint8_t", "uf_cases", packed));
  } else {
    const m = mode.map;
    if (m.publishMask) lines.push("#define UF_PUBLISH_MASK 1");
    // One entry per observable of the circuit (the decoder publishes in a loop over all of them):
    // an observable no core conditions on is group 4, which the decoder does not publish.
    const outs = Array.from({ length: graph.observables.length }, (_, j) => m.outputs[j] ?? { group: 4, slot: 0 });
    if (m.outputs.length > graph.observables.length) throw Error("the run names " + m.outputs.length + " decoder outputs; the circuit has " + graph.observables.length + " observables");
    lines.push(`#define UF_SEGMENTS ${m.segments}`, `#define UF_MEMBERS ${m.members}`, `#define UF_DECODE_SEGMENT ${m.decodeSegment}`,
      arr("uint8_t", "in_group", m.inputs.map((x) => x.group)), arr("uint8_t", "in_slot", m.inputs.map((x) => x.slot)),
      arr("uint8_t", "out_group", outs.map((x) => x.group)), arr("uint8_t", "out_slot", outs.map((x) => x.slot)),
      `static const uint32_t flag_group = ${m.flag.group}, flag_slot = ${m.flag.slot};`);
  }
  return lines.join("\n") + "\n";
}

/** A one-core build for a decoder alone: 64 KiB of RAM at the 500 MHz of the x6y3 build. */
export function benchSpec({ dspHz = 500e6 } = {}) {
  return socSpec({
    name: "uf-decoder", dsp_freq_hz: dspHz, link_pipe: 4,
    core_defaults: { mem_depth: 16384, with_mul: true, queue_depth: 4 },
    cores: [{ name: "dec0.0", channels: [{ name: "status", kind: "dio", slots: 1 }] }],
  });
}

/**
 * Compile the decoder for `graph` in a mode. Returns { elf, bytes, command, pruned }.
 * A hypergraph decoder's tables can outgrow the core's RAM (a few thousand error mechanisms);
 * then only the likeliest mechanisms are kept, as many as fit (they are listed most likely first),
 * and `pruned` says how many were dropped and the probability they carried.
 */
export function build(graph, mode, { spec = benchSpec(), core = 0 } = {}) {
  // Images are kept by the hash of everything the compiler sees (the source, the generated
  // tables and the core's configuration), so a machine without the riscv32 clang (the web
  // server) runs the same image a full run compiled. A missing image needs clang.
  const compile = (g) => {
    const files = { "uf_decoder.c": readFileSync(SOURCE, "utf8"), "uf_graph.h": header(g, mode) };
    const runtime = ["start.S", "muldiv.c", "riscq.h"].map((f) => readFileSync(join(runtimeDir, f), "utf8"));
    const key = createHash("sha256").update(JSON.stringify([files, runtime, mapHeader(spec, core), linkerScript(spec, core), spec.cores[core].withMul])).digest("hex").slice(0, 24);
    const file = join(IMAGES, key + ".json");
    if (existsSync(file)) { const x = JSON.parse(readFileSync(file, "utf8")); if (x.overflow) throw Error(x.overflow); return { elf: new Uint8Array(Buffer.from(x.elf, "base64")), command: x.command }; }
    try {
      const r = compileC(spec, core, files);
      mkdirSync(IMAGES, { recursive: true });
      writeFileSync(file, JSON.stringify({ command: r.command, elf: Buffer.from(r.elf).toString("base64") }));
      return r;
    } catch (error) {
      if (/overflows RAM/.test(error.message)) { mkdirSync(IMAGES, { recursive: true }); writeFileSync(file, JSON.stringify({ overflow: error.message })); }
      throw error;
    }
  };
  try {
    const { elf, command } = compile(graph);
    return { elf, bytes: elf.length, command, pruned: null };
  } catch (error) {
    if (!graph.errors || !/overflows RAM/.test(error.message)) throw error;
  }
  let lo = 1, hi = graph.errors.length - 1, best = null;
  while (lo <= hi) {
    const k = (lo + hi) >> 1;
    try { best = { k, ...compile({ ...graph, errors: graph.errors.slice(0, k) }) }; lo = k + 1; } catch (error) { if (!/overflows RAM/.test(error.message)) throw error; hi = k - 1; }
  }
  if (!best) throw Error("the decoding graph does not fit the decoder core's RAM even with one error mechanism");
  const dropped = graph.errors.slice(best.k);
  return { elf: best.elf, bytes: best.elf.length, command: best.command,
    pruned: { kept: best.k, dropped: dropped.length, droppedProbability: dropped.reduce((s, [, , p]) => s + p, 0), keptProbability: graph.errors.slice(0, best.k).reduce((s, [, , p]) => s + p, 0) } };
}

/** Words of the ELF's loaded image, and how many of the core's RAM words they take. */
export function footprint(elf, spec = benchSpec(), core = 0) {
  const words = loadElf(elf);
  return { words: words.length, ramWords: spec.cores[core].memWords };
}

/**
 * Bench run: decode `cases` (bit strings of one shot each) in the Lean model, `chunk` cases per
 * run (a slow decoder would otherwise exceed the model's step budget).
 */
export async function bench(graph, cases, { spec = benchSpec(), chunk = graph.errors ? 10 : 200 } = {}) {
  if (cases.length > chunk) {
    const parts = [];
    for (let k = 0; k < cases.length; k += chunk) parts.push(await bench(graph, cases.slice(k, k + chunk), { spec, chunk }));
    return { ...parts[0], decodes: parts.flatMap((p) => p.decodes), status: parts.map((p) => p.status).find((s) => s !== "quiescent") ?? parts[0].status };
  }
  const { elf, bytes, pruned } = build(graph, { kind: "bench", cases }, { spec });
  const images = spec.cores.map((_, i) => (i === 0 ? { words: loadElf(elf), sourceMap: [] } : { words: [0x0000006f], sourceMap: [] }));
  const result = await execute(program(spec, images, { trace: "io", maxSteps: 20_000_000, maxEvents: 400_000, maxBatches: 2_000_000_000 }));
  const words = new Map(result.summary.host.filter((h) => h.core === 0).map((h) => [h.offset / 4, h.value >>> 0]));
  const periodNs = spec.dspPeriodPs / 1000;
  const out = [];
  for (let c = 0; c < cases.length; c++) {
    const w = (k) => words.get(c * 7 + k);
    if (w(0) !== c) {
      // The run's step budget ended before the last case: decode the chunk in halves.
      if (cases.length > 1 && result.summary.status !== "quiescent") {
        const half = cases.length >> 1;
        const [x, y] = [await bench(graph, cases.slice(0, half), { spec, chunk: half }), await bench(graph, cases.slice(half), { spec, chunk: half })];
        return { ...x, decodes: [...x.decodes, ...y.decodes], status: y.status };
      }
      throw Error("the decoder stored no result for case " + c + " (status " + result.summary.status + ")");
    }
    out.push({ batches: w(2) - w(1), ns: (w(2) - w(1)) * periodNs, mask: w(3), measured: w(4), defects: w(5), rounds: w(6) });
  }
  return { decodes: out, status: result.summary.status, bytes, periodNs, footprint: footprint(elf, spec), pruned };
}
